// Copies the Luau that tests/flamework2/ compiled into src/bench/codecs/, where the benchmark place
// loads it as the flamework2 column (Benchmark harness 4.10 in docs/specs/benchmark-harness.md).
// `mise run bench:definitions` compiles that project first.
//
// The place cannot compile these serializers itself: Flamework 2's transformer and Flamework 1's,
// which fbs, serio and runit need, write the same flamework.build and include/flamework/.
//
// Each module imports @flamework-experimental/core only to call `Flamework.createSerializer`, which
// returns its one argument when it is given no options. The copy puts a table whose
// `createSerializer` does the same in place of that import, so the place loads no Flamework 2
// package, and the functions the benchmark times are the ones the transformer generated.
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const tests = join(dirname(fileURLToPath(import.meta.url)), "..");
const project = join(tests, "flamework2");
const sources = join(project, "src");
const compiled = join(project, "out");
const codecs = join(tests, "src", "bench", "codecs");

const CORE_IMPORT =
	'local Flamework = TS.import(script, game:GetService("ReplicatedStorage"), "rbxts_include", "node_modules", "@flamework-experimental", "core", "out").Flamework';
const STAND_IN = "local Flamework = { createSerializer = function(serializer) return serializer end }";
const COMPILED_BY = /^-- Compiled with roblox-ts v[^\n]*\n/m;

const transformer = JSON.parse(
	readFileSync(join(project, "node_modules", "@flamework-experimental", "transformer", "package.json"), "utf8"),
).version;

function sourcesUnder(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const path = join(directory, entry.name);
		if (entry.isDirectory()) return sourcesUnder(path);
		return entry.name.endsWith(".ts") ? [path] : [];
	});
}

function fail(message) {
	console.error(message);
	process.exit(1);
}

const written = new Set();
for (const source of sourcesUnder(sources)) {
	const path = relative(sources, source).replace(/\.ts$/, ".luau");
	const fixture = dirname(path);
	if (!existsSync(join(codecs, fixture))) {
		fail(`${relative(tests, source)}: src/bench/codecs/${fixture}/ does not exist.`);
	}

	const luau = readFileSync(join(compiled, path), "utf8");
	const imports = luau.split(/\r?\n/).filter((line) => line.includes("TS.import("));
	if (imports.length !== 1 || imports[0] !== CORE_IMPORT) {
		fail(
			`flamework2/out/${path}: expected one import, of @flamework-experimental/core, and found:\n${imports.join("\n")}`,
		);
	}
	if (!COMPILED_BY.test(luau)) {
		fail(`flamework2/out/${path}: no "-- Compiled with roblox-ts" line to put the header after.`);
	}

	const header = [
		`-- Generated by \`mise run bench:definitions\` from tests/flamework2/src/${relative(sources, source).replaceAll("\\", "/")}`,
		`-- by @flamework-experimental/transformer ${transformer}; do not edit. The Flamework line stands in`,
		"-- for @flamework-experimental/core (Benchmark harness 4.10 in docs/specs/benchmark-harness.md).",
	].join("\n");
	const copy = luau.replace(COMPILED_BY, (line) => `${line}${header}\n`).replace(CORE_IMPORT, STAND_IN);
	writeFileSync(join(codecs, path), copy);
	written.add(join(codecs, path));
}

// A generated module whose source is gone would otherwise stay in the place as a column cell.
for (const fixture of readdirSync(codecs)) {
	for (const name of readdirSync(join(codecs, fixture))) {
		const path = join(codecs, fixture, name);
		if (/^flamework2(-.+)?\.luau$/.test(name) && !written.has(path)) {
			rmSync(path);
		}
	}
}

console.log(`Copied ${written.size} Flamework 2 codec modules into src/bench/codecs/.`);
